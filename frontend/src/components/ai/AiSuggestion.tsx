import type { Suggestion } from "../../types";
import { useSuggestion } from "./useSuggestion";
import "./AiSuggestion.css";

export default function AiSuggestion({ patientId, highlight }: { patientId: string; highlight?: string }) {
  const { state, run } = useSuggestion(patientId);

  if (state.status !== "done") {
    return (
      <div className="ai-bar">
        <button type="button" className="button primary" onClick={run} disabled={state.status === "loading"}>
          {state.status === "loading" ? "Asking…" : "Ask AI"}
        </button>
        {state.status === "error" && <span className="ai-error">{state.message}</span>}
      </div>
    );
  }

  return <SuggestionPanel s={state.result} highlight={highlight} onRegenerate={run} />;
}

function SuggestionPanel({ s, highlight, onRegenerate }: { s: Suggestion; highlight?: string; onRegenerate: () => void }) {
  // On a review card, show the drug being judged first
  const drugs = highlight
    ? [...s.drugs].sort((a, b) => Number(b.name === highlight) - Number(a.name === highlight))
    : s.drugs;

  return (
    <div className="ai-panel">
      <div className="ai-head">
        <span className="ai-label">AI draft</span>
        <span className={`pill conf-${s.confidence}`}>{s.confidence} confidence</span>
        <button type="button" className="text-button ai-regen" onClick={onRegenerate}>Regenerate</button>
      </div>
      {s.most_likely && (
        <p className="ai-likely">
          Most likely: <strong>{s.most_likely}</strong>
        </p>
      )}
      <p className="ai-summary">{s.summary}</p>

      {drugs.map((d) => (
        <div key={d.name} className={d.name === highlight ? "ai-drug highlighted" : "ai-drug"}>
          <div>
            <strong>{d.name}</strong> <span className="muted">· {d.assessment}</span>
          </div>
          {d.explains && d.explains.length > 0 && (
            <div className="chips ai-explains">
              <span className="muted">Could explain:</span>
              {d.explains.map((r) => <span key={r} className="chip reaction-chip">{r}</span>)}
            </div>
          )}
          <ul className="ai-reasons">
            {d.reasons.map((r, i) => (
              <li key={i}>
                {r.text}
                {r.evidence.length === 0 && (
                  <span className="uncited" title="Not backed by the collected evidence; from the model's general knowledge">
                    general knowledge
                  </span>
                )}
                {r.evidence.map((e) => (
                  <details key={e.id} className="cite">
                    <summary>{e.id}</summary>
                    <span className="cite-body">
                      <em>{e.drug}</em>: {e.text}
                    </span>
                  </details>
                ))}
              </li>
            ))}
          </ul>
        </div>
      ))}

      {s.unexplained_reactions && s.unexplained_reactions.length > 0 && (
        <div className="ai-section">
          <h4 className="reason-title">Not well explained by any drug</h4>
          <div className="chips">
            {s.unexplained_reactions.map((r) => <span key={r} className="chip reaction-chip">{r}</span>)}
          </div>
        </div>
      )}

      {s.missing_information.length > 0 && (
        <div className="ai-section">
          <h4 className="reason-title">Would change the assessment</h4>
          <ul className="ai-reasons">
            {s.missing_information.map((m, i) => <li key={i}>{m}</li>)}
          </ul>
        </div>
      )}
      <p className="muted ai-footnote">Generated by {s.model}. Check cited evidence before relying on it.</p>
    </div>
  );
}
